@dataclass
class StrategyConfig:
    """多因子信号引擎参数。

    === 关键设计：因子权重不是常数 ===
    本配置只定义因子的「计算窗口」与「候选权重上限」，
    实际生效的权重由 `AdaptiveWeighter` 依据近期实测预测力在线决定。

    这样做的原因：任何"某因子在此市场有效/无效"的结论，
    都必须来自对**已观测价格序列**的统计推断，
    不能来自对目标系统内部机制的了解。
    """

    # 因子计算窗口
    ema_fast: int = 8
    ema_slow: int = 34
    roc_window: int = 12
    roc_scale: float = 0.012
    zscore_window: int = 30
    zscore_cap: float = 2.5
    atr_window: int = 20
    slope_window: int = 34

    # 自适应权重
    adapt_lookback: int = 400          # 用最近多少条因子记录评估预测力
    adapt_min_samples: int = 60        # 少于该样本数则先验为 0（不下注）
    adapt_temperature: float = 1.5     # softmax 温度，越大越平均
    adapt_shrinkage: float = 0.75      # 向 0 收缩的强度，抑制追噪声
    #
    # 因子显著性门槛（t 统计量）。
    #
    # 这曾设为 2.0（约 95% 置信度），结果造成"过度保守"的死锁：
    # 真实 IC 约 0.05 的因子，要达到 t=2.0 需要上千个独立样本，
    # 而回看窗口只有几百，于是任何因子都永远不显著 -> 权重恒为 0
    # -> 永不交易 -> 在线校准也永远拿不到样本。整条链自我锁死。
    #
    # 取 1.0（约单边 84% 置信度）是更现实的选择：实盘里 IC≈0.05 的
    # 信号本来就达不到 95% 置信度，强行要求只会导致策略完全不动作。
    # 噪声风险由下游两道防线兜住 —— 在线校准的成本门槛 + 风控。
    adapt_t_threshold: float = 1.0
    weight_floor: float = 0.0
    max_weight: float = 0.7            # 单因子权重上限，防止独大

    # 信号阈值
    #
    # 门槛决定交易频率。手续费是确定成本，而在无预测力的环境里
    # 每笔交易的期望收益为负，因此「少交易」本身就是正收益策略。
    # 门槛越高，交易越少，成本侵蚀越小。
    #
    # === 为什么从 0.45 降到 0.35 ===
    # 合成 score = Σ(因子×权重)/Σ|权重|，再乘波动率调节，
    # 量级本身就不大（典型活跃区间只有 ±0.2 ~ ±0.5）。
    # 实测 0.45 在真实游戏行情里**几乎不产生任何开仓意图**：
    # 学习器即使确认了若干显著因子、权重非零，
    # 合成后的 |score| 也长期落在 0.2~0.4 之间，卡在阈值下方空转。
    # 0.35 是"能看到实际交易、又不至于把噪声全部放行"的位置 ——
    # 真正决定该不该下注的是下游的在线校准成本门槛，
    # 信号阈值只负责把最弱的那批过滤掉，不应越俎代庖。
    entry_score: float = 0.35
    score_cap: float = 1.5

    # ------------------------------------------------------------------
    # 成本感知开仓门槛（Cost-Aware Entry Gate）
    # ------------------------------------------------------------------
    #
    # === 动机 ===
    # 记账游戏的交易成本是**确定支出**，而信号只是**概率优势**。
    # 在缺乏预测力的行情里，每笔交易的期望毛收益约为 0，
    # 此时交易越多，净亏损越大（成本侵蚀）。
    #
    # 因此开仓不应只看「信号够不够强」，还要看
    # 「这点信号强度换来的预期收益，够不够覆盖交易成本」。
    #
    # === 全部输入都来自公开信息 ===
    #   - score        : 我们自己用价格历史算出来的
    #   - 手续费规则   : 游戏界面公开展示（见 trade_fee）
    #   - 点差         : 玩家在界面上能直接观察到的买卖价差
    # 不依赖任何未公开的内部实现。
    #
    cost_gate_enabled: bool = True

    # 预期收益 = |score| × score_to_return。
    # 这是一个**保守**的映射：假定 score=1.0 时，单笔往返
    # 预期毛利仅为名义价值的 0.5%。宁可低估自己的优势。
    score_to_return: float = 0.005

    # 成本倍数门槛：预期毛利必须 ≥ 往返成本 × cost_multiple。
    #
    # === 为什么最终定在 3.0 ===
    # 在自建评估台上扫描 1.5 / 3.0 / 6.0 / 12.0（12 个种子 × 5 档市场）：
    #   1.5 档：flat（纯随机）居然是 +1.96%（t=+3.8）——
    #           这是"假利润"的典型特征：在没有结构的市场上系统性地赚，
    #           说明门槛太松，放行了大量"预期收益被噪声高估"的交易。
    #   3.0 档：flat 回到 -0.67%（t=-0.5，与 0 不可区分），
    #           同时 trend +1.44%（t=+2.4）、trend_mod +1.66%（t=+2.0）
    #           依然显著为正 —— 既捕捉了结构，又没有在噪声上乱下注。
    #   6.0/12.0 档：过严，趋势市场的优势也被一起挡掉（收益趋近 0）。
    # 因此 3.0 是"该赚的还赚、不该赚的不碰"的平衡点。
    cost_multiple: float = 3.0

    # 界面上可观察到的点差估计（单边，占价格比例）。
    #
    # === 为什么默认是 0 ===
    # 实测该游戏的行情接口只提供**单一价格**（浏览器桥接从报价元素里
    # 只读到一个数值），界面上并没有并列的买入价/卖出价。
    # 也就是说，开仓与平仓都按同一个当前价成交，点差成本约为 0。
    #
    # 早期版本把它设成 0.0008（8bp）是**过度保守**的臆测：在 5 倍杠杆下，
    # 往返成本被抬高到约 9.5bp，而信号的真实预期优势通常只有几个 bp，
    # 结果是成本门槛把所有交易全部挡掉、策略永远空仓。
    #
    # 真实的确定成本只有手续费（见 trade_fee），5 倍杠杆往返约 1.5bp。
    # 若将来观察到界面存在真实买卖价差，把它调到对应值即可
    # （命令行 `--spread`，例如 --spread=0.0002）。
    spread_estimate: float = 0.0

    # ------------------------------------------------------------------
    # 周期/谱因子
    # ------------------------------------------------------------------
    #
    # === 动机 ===
    # 普通的动量/反转因子只能捕捉「相邻时点」的自相关。若价格里存在
    # 周期性成分（这在真实的外汇/商品市场里很常见），单周期动量往往
    # 测不出来：一个完整周期走下来，净位移接近零，动量因子自然失效。
    #
    # 正确做法是**谱分析**：把价格序列分解到不同频率上，找到能量最强
    # 的那个频率，估计它的相位，再外推一个时点。
    #
    # === 不预设任何具体周期 ===
    # 周期从 min 到 max 全范围扫描，究竟哪个频率有效、是否存在周期，
    # 完全由数据本身决定。若没有任何频率能显著解释方差，
    # 因子返回 0 —— 即"未发现周期结构"。
    #
    # 扫描采用**正交频率网格**（周期 = W/k，即离散傅里叶变换的天然格点）。
    # 早期版本用一组离散的整数周期（4,6,8,...），当真实周期不在格点上时
    # 会发生频谱泄漏，功率大幅下降，导致明明有周期却检测不出来。
    cycle_window: int = 128                 # 用于谱分析的收益样本数
    cycle_min_period: float = 4.0           # 考察的最短周期（轮）
    cycle_max_period: float = 48.0          # 考察的最长周期（轮）
    cycle_min_frac: float = 0.04            # 最强频率至少解释的方差比例
    #
    # 输出尺度的下限。因子输出用**当期波动率**归一化
    # （预测漂移 / 收益标准差），这样它的量级能与其他因子可比，
    # 从而被自适应权重机制正常记录与学习。该下限仅用于防止
    # 极低波动时数值爆表。
    cycle_scale: float = 0.0003

    # ------------------------------------------------------------------
    # 分数校准（自校准的成本门槛）
    # ------------------------------------------------------------------
    # 用已实现的价格在线估计「score -> 预期收益」的映射，
    # 取代硬编码的 score_to_return 假设，使成本门槛自动适配信号真实强度。
    calib_lookback: int = 300               # 用于回归的样本窗口
    calib_min_samples: int = 50             # 少于该样本数则先验为 0（不下注）
    # 还要求窗口内有足够多的**非零** score 才算"就绪"。
    # 策略刚起步时权重全零、score 恒等于 0，这些 0 样本会让样本数
    # 迅速凑够，使校准器在只有几个非零 score 时就宣布可用，
    # 算出一个噪声主导的 β 并据此否决全部交易。
    calib_min_nonzero: int = 20
    # 校准未就绪时是否允许交易。
    #
    # False（默认）：退回命名常数 score_to_return 估算预期收益。
    #   好处是不会死锁 —— 只要学习器给出权重就能交易。
    #   代价是在随机行情里会拿"未经验证的常数假设"去做单，
    #   实测会在无结构市场上小亏（赚不到钱但白付波动）。
    # True：校准就绪前一律不下注。
    #   更保守，但**有死锁风险**：若学习器始终找不到显著因子，
    #   权重恒为零 → score 恒为零 → 校准永远不就绪 → 永不交易。
    require_calibration: bool = False



@dataclass
class RiskConfig:
    """风控与仓位参数（全部为通用量化风控，不依赖目标市场特性）。"""

    risk_per_trade: float = 0.006
    max_positions: int = 2
    leverage: int = 5
    atr_stop_multiple: float = 2.0
    atr_take_multiple: float = 3.5
    trailing_start: float = 1.0
    trailing_step: float = 0.8
    min_liquidation_buffer: float = 0.55
    # 单笔保证金上限占权益比例。与 risk_per_trade、止损距离共同作用，
    # 三者中取最保守的结果，防止仓位在极端参数下失控。
    max_margin_fraction: float = 0.12
    daily_loss_limit: float = 0.08
    allow_loan: bool = False
    max_holding_bars: int = 900

    # ------------------------------------------------------------------
    # 盈利保护 / 回吐锁（Profit Guard）
    # ------------------------------------------------------------------
    #
    # === 要解决的问题：「本来盈利，拖到亏损」 ===
    # 早期只设了止损和"很远的"追踪止盈，结果两边都形同虚设：
    # 实测一笔持仓的浮盈峰值中位数只有保证金的 **3.5%**，
    # 而追踪止盈要等到浮盈达保证金的 60% 才启动 —— 从来没启动过。
    # 于是离场只剩「信号反转」与「持仓超时」两条路，
    # 而信号反转往往发生在价格已经反向走了一段之后：
    # 一笔曾经浮盈的单子，最后经常以亏损收场。
    #
    # === 判据用「占保证金的比例」，不用绝对金额，也不用 ATR ===
    # r = 浮盈 / 保证金。这个口径自我标定：
    # 不管是 5 倍还是 20 倍杠杆、仓位是大是小，
    # "这笔赚了本金的百分之几"永远是同一个意思。
    # 也因此在只有单一报价（ATR 退化）的行情源里依然可用。
    #
    # === 规则本身只有一句话 ===
    # 浮盈峰值达到 arm 之后，就允许回吐，但最多回吐 giveback 的比例，
    # 并且**永不低于保本**（下限被抬到 0）。
    #     floor = max(0, peak × (1 − giveback))
    # 一旦 r 跌回 floor 就离场。
    #   peak = 2%、giveback = 0.5  →  floor = 1%   （锁定 1%）
    #   peak = 8%、giveback = 0.5  →  floor = 4%   （锁定 4%）
    # 「不低于保本」这一条就是关键：赚过钱的单子不会再变成亏损单。
    #
    # === 参数取值：arm = 1.0%，giveback = 40%（由扫描定案）===
    #
    # 扫描口径：合成市场 8 档 × 12 种子 × 1500 轮，逐组试算
    # （脚本 `tools/sweep_profit_guard.py`，日志 logs/_sweep_guard*.txt）。
    #
    #   配置              结构档均值    flat    趋势档(trend_mod)
    #   关闭保护(旧)        +9.71%     -0.72%      +4.52%
    #   arm0.3% give20%    +29.63%     +0.83%     +43.89%   ← 疑似仿真伪影
    #   arm1.0% give40%    +18.40%     +0.42%     +24.60%   ← 本版选定
    #   arm1.0% give50%    +17.18%     +0.27%     +24.85%
    #   arm2.0% give50%    +16.02%     +0.06%     +20.56%
    #   arm3.0% give50%    +14.40%     -0.28%     +15.18%
    #   arm5.0% give50%    +12.85%     -0.63%     +9.55%
    #
    # === 为什么不选扫描最高的 arm0.3% give20% ===
    # 那一档 trend_strong 冲到 +152%，且**越紧越好、单调无上界**。
    # 这是"退出后立刻同价重进"在零成本仿真里的churn 伪影，
    # 不是真实可提取的利润（实盘要付手续费、要排队成交）。
    # 取 arm1.0% 是"明显改善结构档、又没踩在伪影悬崖上"的位置。
    #
    # arm=1% 的依据：实测浮盈峰值中位 ~3.5%，
    # 1% 远低于它 → 绝大多数"真的走对方向"的单子都会进入保护状态；
    # 同时高过纯噪声（±0.5%），不会把抖动当盈利来锁。
    # 注意：合成市场只是初筛，**权威校准应来自真实盘口** ——
    # live 收尾会打印"浮盈峰值中位 / 平仓留存中位"两个统计量，
    # 若峰值中位长期显著低于 1%，说明该市场给不出这么大的波段，
    # 应把 arm 相应调小。
    profit_guard_arm: float = 0.01
    profit_guard_giveback: float = 0.4

    # 灾难止损：浮亏达保证金的比例，直接砍。
    #
    # 这是**兜底**，不是主要离场手段 —— 常规离场交给盈利保护和信号反转。
    #
    # 取值 0.35 不是拍脑袋，而是与回测侧的判据对齐：
    # 回测走 RiskManager.should_force_exit → liquidation_buffer_ok，
    # 该判据在 risk_ratio > (1 − min_liquidation_buffer) × LIQUIDATION_RATIO
    # 时强制离场，即 (1 − 0.55) × 0.80 = **0.36**。
    # 而 live 侧原来用的是 0.55 —— 比回测松得多，
    # 等于同一套风控在两个执行路径下行为不一致。
    # 统一到 0.35（略紧于 0.36，留一点余量）后两边口径一致。
    #
    # 参考：游戏爆仓线是亏损 80% 保证金，5 倍杠杆下对应价格逆行 16%，
    # 0.35 留了充足缓冲。
    hard_stop_ratio: float = 0.35


@dataclass
class EngineConfig:
    strategy: StrategyConfig = field(default_factory=StrategyConfig)
    risk: RiskConfig = field(default_factory=RiskConfig)
    seed: int | None = None
    fee_enabled: bool = True

    # 评估因子预测力时，向前看多少根 K 线（注意：这是评估已实现的过去，
    # 而不是预测未来 —— 用于给因子打分的记录在结算时已经"过期"，
    # 策略在决策时点只能看到已结算的历史记录）
    #
    # 取值依据：实测各因子在自建市场（含趋势/均值回归结构）上的信息系数(IC)
    # 随预测周期的衰减——IC 在 h=1 最大（如动量 0.057），到 h=20 已衰减到约
