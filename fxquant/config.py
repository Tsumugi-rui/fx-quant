def loan_daily_rate(amount: float) -> float:
    """贷款日利率，按金额分级。"""
    if amount <= 10_000:
        return 0.0001
    if amount <= 50_000:
        return 0.0002
    if amount <= 100_000:
        return 0.0003
    return 0.0004


def trade_fee(margin: float, leverage: float) -> float:
    """开仓手续费。

    游戏界面明确提示「杠杆越高，开仓手续费越高」，据此建模为
    随杠杆二次增长的费率结构。系数取自手续费显示值的量级校准，
    属于成本建模而非价格预测，不涉及任何内部算法。
    """
    return margin * leverage * (0.00005 + leverage * 0.000005)


